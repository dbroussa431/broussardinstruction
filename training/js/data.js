(function enhancePortalData() {
  function slugify(value) {
    return String(value || "")
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "");
  }

  if (!Array.isArray(window.LESSONS)) window.LESSONS = [];
  if (!window.QUIZ_BANK || typeof window.QUIZ_BANK !== "object") window.QUIZ_BANK = {};

  window.LESSONS = window.LESSONS.map((lesson, lessonIndex) => ({
    ...lesson,
    id: Number(lesson.id || lessonIndex + 1),
    slug: lesson.slug || slugify(lesson.title || `lesson-${lessonIndex + 1}`),
    estTime: lesson.estTime || "18 min",
    summary: lesson.summary || "Lesson summary unavailable.",
    sections: Array.isArray(lesson.sections) ? lesson.sections : [],
    scenarios: Array.isArray(lesson.scenarios) ? lesson.scenarios : []
  }));

  Object.keys(window.QUIZ_BANK).forEach((lessonId) => {
    const lesson = window.LESSONS.find((item) => Number(item.id) === Number(lessonId));
    const lessonSlug = lesson?.slug || `lesson-${lessonId}`;

    window.QUIZ_BANK[lessonId] = (window.QUIZ_BANK[lessonId] || []).map((question, questionIndex) => {
      const id = question.id || `L${lessonId}_${lessonSlug}_${String(questionIndex + 1).padStart(3, "0")}`;
      const difficulty = question.difficulty || (question.type === "tf" ? "easy" : (question.choices?.length >= 4 ? "medium" : "easy"));
      const category = question.category || (lesson?.title || "General Knowledge");

      return {
        ...question,
        id,
        difficulty,
        category
      };
    });
  });
})();
